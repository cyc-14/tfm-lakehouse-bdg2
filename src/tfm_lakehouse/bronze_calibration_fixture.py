"""Deterministic, invented input for the D45 Bronze calibration."""

from collections.abc import Callable, Iterable, Iterator
from datetime import datetime, timedelta
import hashlib


def fixture_layout(hours: int, buildings_count: int) -> dict[str, tuple[list[str], int]]:
    """Return the fixed CSV headers and row counts, without generating rows."""
    supported_hours = {16: (8, 625, 6250, 17544), 1600: (8, 512, 17544)}
    if (type(hours) is not int or type(buildings_count) is not int or
            hours not in supported_hours.get(buildings_count, ())):
        raise ValueError("Unsupported synthetic fixture size")
    return {
        "electricity": (["timestamp", *(f"SYNTHETIC_building_{i:02d}"
                                       for i in range(buildings_count))], hours),
        "metadata": (["building_id", "site_id", "primaryspaceusage",
                      "sub_primaryspaceusage", "sqm", "timezone"], buildings_count),
        "weather": (["timestamp", "site_id", "airTemperature", "precipDepth1HR"], hours * 4),
    }


def fixture_lines(name: str, columns: list[str], rows: int, buildings_count: int) -> Iterator[bytes]:
    """Yield one complete LF-terminated CSV record at a time."""
    yield (",".join(columns) + "\n").encode("utf-8")
    for index in range(rows):
        if name == "metadata":
            site = (index // 4) % 4
            line = (f"SYNTHETIC_building_{index:02d},SYNTHETIC_SITE_{site:02d},"
                    f"Lodging/residential,Synthetic,{100 + index},Europe/London")
        else:
            hour, site = divmod(index, 4) if name == "weather" else (index, 0)
            timestamp = (datetime(2016, 1, 1) + timedelta(hours=hour)).isoformat(sep=" ")
            if name == "weather":
                line = f"{timestamp},SYNTHETIC_SITE_{site:02d},{hour + site},0"
            else:
                start = hour * buildings_count
                line = ",".join([timestamp, *(str(value) for value in range(start, start + buildings_count))])
        yield (line + "\n").encode("utf-8")


def source_fingerprint(
    lines: Iterable[bytes], consume: Callable[[bytes], None] | None = None,
) -> dict[str, str | int]:
    """Hash and count bytes as each record is generated, written or checked."""
    total = 0
    digest = hashlib.sha256()
    for line in lines:
        if consume is not None:
            consume(line)
        total += len(line)
        digest.update(line)
    return {"bytes": total, "sha256": digest.hexdigest()}


def fixture_manifest(hours: int = 8, buildings_count: int = 16) -> dict[str, dict[str, str | int]]:
    """Describe the exact generated bytes without inspecting any input paths."""
    return {
        name + ".csv": source_fingerprint(fixture_lines(name, columns, rows, buildings_count))
        for name, (columns, rows) in fixture_layout(hours, buildings_count).items()
    }
